#!/usr/bin/env python3
"""Index the hero portraits so the pages know exactly which members have one.

Scans images/heroes/*.jpg and writes js/portraits.js:

    window.JLDEX_PORTRAITS = { "superman": 1, "batman": 1, ... };

Listing them explicitly (instead of probing the file system from the browser)
keeps requests honest: members without a portrait fall back to their crest and
the page never asks for a file that does not exist.

Run:  python3 tools/index_portraits.py
"""
import json, os, re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
HERO_DIR = os.path.join(ROOT, "images", "heroes")
OUT = os.path.join(ROOT, "js", "portraits.js")


def data_slugs():
    """Slugs referenced by the dex records (images/<slug>.svg)."""
    with open(os.path.join(ROOT, "js", "data.js")) as fh:
        return set(re.findall(r"images/([a-z0-9\-]+)\.svg", fh.read()))


def main():
    have = sorted(
        os.path.splitext(f)[0]
        for f in os.listdir(HERO_DIR)
        if f.lower().endswith((".jpg", ".jpeg", ".png"))
    )
    unknown = [s for s in have if s not in data_slugs()]
    lines = [
        "// Generated by tools/index_portraits.py — members with a hero portrait.",
        "// Anything not listed here falls back to its archive crest.",
        "window.JLDEX_PORTRAITS = {",
    ]
    lines += ['  "%s": 1,' % s for s in have]
    lines.append("};")
    with open(OUT, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("portraits indexed: %d/%d members" % (len(have), len(data_slugs())))
    if unknown:
        print("WARNING: portraits with no matching dex record:", ", ".join(unknown))


if __name__ == "__main__":
    main()
